/// Authentic morning / evening adhkar + Surah al-Mulk, used by the full-screen
/// adhkar display. Sources are from the Qur'an and the Sunnah (Hisn al-Muslim).
library;

class Dhikr {
  final String text;
  final String count; // e.g. '×٣' or ''
  final String source;
  const Dhikr(this.text, {this.count = '', this.source = ''});
}

enum AdhkarType { morning, evening, mulk }

AdhkarType adhkarTypeFromString(String s) {
  switch (s) {
    case 'morning':
      return AdhkarType.morning;
    case 'evening':
      return AdhkarType.evening;
    default:
      return AdhkarType.mulk;
  }
}

String adhkarTitle(AdhkarType t) {
  switch (t) {
    case AdhkarType.morning:
      return 'أذكار الصباح';
    case AdhkarType.evening:
      return 'أذكار المساء';
    case AdhkarType.mulk:
      return 'سورة المُلك';
  }
}

String adhkarSubtitle(AdhkarType t) {
  switch (t) {
    case AdhkarType.morning:
      return '﴿فَسُبْحَانَ اللَّهِ حِينَ تُمْسُونَ وَحِينَ تُصْبِحُونَ﴾';
    case AdhkarType.evening:
      return 'حصّن نفسك بذكر الله قبل دخول الليل';
    case AdhkarType.mulk:
      return 'المانعةُ المنجيةُ من عذاب القبر';
  }
}

